require("dotenv").config({ quiet: true });
const sequelize = require("../config/database");
sequelize.options.logging = false;
const { Product, ProductAvailability } = require("../models/product.model");
(async () => {
  const query = sequelize.getQueryInterface();
  const columns = await query.describeTable(Product.getTableName());
  if (!columns.stockQuantity) await query.addColumn(Product.getTableName(), "stockQuantity", Product.rawAttributes.stockQuantity);
  await require("../models/resource-availability.model").sync();
  await require("../models/booking-email.model").sync();
  // These rows were generated by our demo seeds, not entered by an administrator.
  await ProductAvailability.destroy({ where: { note: ["Booking design schedule — Pacific time", "Pacific time (America/Los_Angeles)"] } });
  console.log("Inventory and monthly availability ready. Seed-generated schedules removed; custom schedules preserved. Unscheduled resources default to 24/7.");
})().catch(error => { console.error(error.name); process.exitCode = 1; }).finally(() => sequelize.close());
