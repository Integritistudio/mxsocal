require('dotenv').config({ quiet: true });
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const request = require('supertest');
const express = require('express');
const sharp = require('sharp');
const db = require('../config/database'); db.options.logging = false;
const User = require('../models/user.model');
const Story = require('../models/story.model');
const { cleanDocument } = require('../lib/story-content');
const { generateToken } = require('../helpers/jwt');
const app = express(); app.use(express.json()); app.use(require('cookie-parser')()); app.use('/stories', require('../routes/story.route'));
(async () => {
  let id, filename, customer;
  const slug = `story-check-${crypto.randomUUID()}`;
  try {
    await Story.sync();
    const admin = await User.findOne({ where: { role: 'admin' } }); assert(admin);
    const adminToken = generateToken(admin.id, admin.role, admin.tokenVersion);
    customer = await User.create({ name: 'Story Access Test', email: `${slug}@example.com`, role: 'user', emailVerifiedAt: new Date() });
    const customerToken = generateToken(customer.id, customer.role, customer.tokenVersion);
    const call = (method, url, token = adminToken) => request(app)[method](url).set('Authorization', `Bearer ${token}`);
    await request(app).get('/stories/admin').expect(401);
    await call('get', '/stories/admin', customerToken).expect(403);
    await call('post', '/stories/admin', customerToken).send({ title: 'Unauthorized', slug }).expect(403);
    await call('post', '/stories/media', customerToken).attach('images', Buffer.from('bad'), 'photo.png').expect(403);
    await call('post', '/stories/admin').send({ title: 'Test', slug: 'admin' }).expect(400);
    const content = { type: 'doc', content: [{ type: 'heading', attrs: { level: 2, style: 'color:red' }, content: [{ type: 'text', text: 'A useful heading' }] }, { type: 'paragraph', content: [{ type: 'text', text: 'An original story with a ', marks: [{ type: 'bold' }] }, { type: 'text', text: 'website link', marks: [{ type: 'link', attrs: { href: '/bikes', onclick: 'evil()' } }] }] }] };
    const draft = await call('post', '/stories/admin').send({ title: 'Test Story', slug, content, status: 'draft' }).expect(201); id = draft.body.id;
    assert.equal(draft.body.content.content[0].attrs.style, undefined);
    assert.equal(draft.body.content.content[1].content[1].marks[0].attrs.onclick, undefined);
    await request(app).get(`/stories/${slug}`).expect(404);
    const publicList = await request(app).get(`/stories?q=${slug}`).expect(200); assert.equal(publicList.body.total, 0);
    await call('patch', `/stories/admin/${id}`).send({ status: 'published' }).expect(400);
    const image = await sharp({ create: { width: 40, height: 30, channels: 3, background: '#de2321' } }).png().toBuffer();
    await call('post', '/stories/media').attach('images', Buffer.from('fake'), 'photo.png').expect(400);
    const upload = await call('post', '/stories/media').attach('images', image, 'photo.png').expect(201); filename = upload.body.coverImage.split('/').pop();
    await request(app).get(`/stories/media/${filename}`).expect(200).expect('Content-Type', /image\/png/);
    await call('patch', `/stories/admin/${id}`).send({ coverImage: upload.body.coverImage, coverAlt: 'Test cover', excerpt: 'A test article.', category: slug, status: 'published', featured: true, seoTitle: 'Custom search title', seoDescription: 'A custom search description.' }).expect(200);
    const published = await request(app).get(`/stories/${slug}`).expect(200); assert.equal(published.body.story.slug, slug); assert(published.body.story.readingMinutes >= 1); assert.equal(published.body.story.seoTitle, 'Custom search title');
    const filtered = await request(app).get(`/stories?category=${slug}&q=Test`).expect(200); assert.equal(filtered.body.total, 1); assert.equal(filtered.body.stories[0].id, id); assert(!('content' in filtered.body.stories[0]));
    await request(app).get('/stories?page=bad').expect(400);
    await call('post', '/stories/admin').send({ title: 'Duplicate', slug }).expect(409);
    const bad = { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Bad link', marks: [{ type: 'link', attrs: { href: 'javascript:alert(1)' } }] }] }] };
    await call('patch', `/stories/admin/${id}`).send({ content: bad }).expect(400);
    assert.throws(() => cleanDocument({ type: 'doc', content: [{ type: 'script' }] }));
    const sitemap = await request(app).get('/stories/sitemap').expect(200); assert(sitemap.body.some(story => story.slug === slug));
    await call('patch', `/stories/admin/${id}`).send({ status: 'draft' }).expect(200);
    await request(app).get(`/stories/${slug}`).expect(404);
    const sitemapAfter = await request(app).get('/stories/sitemap').expect(200); assert(!sitemapAfter.body.some(story => story.slug === slug));
    await call('delete', `/stories/admin/${id}`).expect(200); id = null;
    console.log('Passed: story CRUD, draft privacy, publish validation, search/category filters, slug uniqueness, safe rich text, uploaded images, sitemap visibility, and admin-only access.');
  } finally {
    if (id) await Story.destroy({ where: { id } });
    if (customer) await customer.destroy();
    if (filename) await fs.unlink(path.resolve(__dirname, '../uploads/story-images', filename));
    await db.close();
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
